const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:8067/')&&!r.url().startsWith('data:'))external.push(r.url());});
  await page.goto('http://127.0.0.1:8067/');
  const click=async name=>page.getByRole('button',{name,exact:true}).last().click();
  const input=page.getByRole('textbox',{name:'Сообщение боту'});
  const send=async text=>{await input.fill(text);await input.press('Enter');};
  await page.locator('.message').last().waitFor();
  fs.mkdirSync('doc/qa',{recursive:true});
  await page.screenshot({path:'doc/qa/candidate-bots-desktop.png',fullPage:true});
  await click('Приглашения');
  await page.locator('[data-action="accept:o1"]').last().click();
  let s=await page.evaluate(()=>JSON.parse(localStorage.getItem('fsp-candidate-bots-v1')).state);
  assert.deepEqual(s.contactsSharedWith,[]);
  await click('Подтверждаю: открыть контакт');
  await click('MAX');await send('/offers');
  assert.match(await page.locator('.message[data-kind="offer"]').nth(-2).innerText(),/Принято/);
  await page.locator('[data-action="decline:o2"]').last().click();await click('Не подходит формат');
  await send('/settings');await click('Выключить уведомления');
  await click('＋ Новое приглашение');
  assert.equal(await page.locator('[data-kind="notification"]').count(),0);
  await send('/offers');assert.match(await page.locator('.message').last().innerText(),/Маяк/);
  await click('Telegram');assert.equal(await page.locator('[data-kind="notification"]').count(),1);
  await page.reload();
  s=await page.evaluate(()=>JSON.parse(localStorage.getItem('fsp-candidate-bots-v1')).state);
  assert.deepEqual(s.contactsSharedWith,['o1']);assert.equal(s.offers[1].status,'declined');assert.equal(s.channels.max.notifications,false);
  await send('Кто видит контакты?');assert.match(await page.locator('.message').last().innerText(),/только пригласившая компания/);
  await send('<img src=x onerror="window.injected=true">');
  assert.equal(await page.evaluate(()=>!!window.injected),false);
  // Reset is scoped to the bot; other prototype data must survive.
  await page.evaluate(()=>localStorage.setItem('unrelated-demo','keep'));
  await click('↺ Сбросить демо');assert.equal(await page.evaluate(()=>localStorage.getItem('unrelated-demo')),'keep');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await send('/offers');
  await page.screenshot({path:'doc/qa/candidate-bots-mobile.png',fullPage:true});
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')),'Отправить сообщение');
  await page.evaluate(()=>localStorage.setItem('fsp-candidate-bots-v1','{broken'));await page.reload();
  assert.match(await page.locator('.message').first().innerText(),/Это демо/);
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked');}});});
  const p=await blocked.newPage();p.on('pageerror',e=>errors.push(e.message));await p.goto('http://127.0.0.1:8067/');
  await p.getByRole('textbox',{name:'Сообщение боту'}).fill('/profile');await p.getByRole('textbox',{name:'Сообщение боту'}).press('Enter');
  assert.match(await p.locator('.message').last().innerText(),/Junior/);assert.match(await p.locator('.composer-note').innerText(),/Сохранение недоступно/);
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  const evidence={status:'PASS',base:'ce709f85e8fe5a5ad63d79b5e71f9a7778eb19f5',checked_at:new Date().toISOString(),url:'http://127.0.0.1:8067/',scenarios:['desktop','mobile-390','explicit-consent','shared-decisions','decline','notification-opt-out','notification-delivery','reload','FAQ-search','HTML-escaping','scoped-reset','keyboard-send','corrupt-storage','blocked-storage','no-external-requests'],browserErrors:errors,externalRequests:external};
  fs.writeFileSync('doc/qa/candidate-bots-browser.json',JSON.stringify(evidence,null,2)+'\n');console.log(JSON.stringify(evidence,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
