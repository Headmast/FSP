// Creates only its own synthetic demo accounts. Use an isolated local database.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');const fs=require('node:fs');
(async()=>{
 const url=process.argv[2]||'http://127.0.0.1:8041';
 assert.match(new URL(url).hostname,/^(127\.0\.0\.1|localhost)$/,'Use only an isolated localhost demo');
 const browser=await chromium.launch({headless:true});
 const errors=[];const contexts=[];
 const register=async role=>{
  const context=await browser.newContext();contexts.push(context);
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url+'/accounts/register/');
  await page.locator('[name=email]').fill(`draft-${role}-${Date.now()}@demo.invalid`);
  await page.locator('[name=role]').selectOption(role);await page.locator('[name=processing_consent]').check();
  for(const name of ['password1','password2'])await page.locator(`[name=${name}]`).fill('Synthetic-drafts-2026!');
  await page.getByRole('button',{name:'Зарегистрироваться'}).click();
  await page.getByRole('button',{name:'Подтвердить demo email'}).click();
  return page;
 };
 const candidate=await register('candidate');
 await candidate.goto(url+'/assistant/');
 assert.equal(await candidate.locator('[name=identifier]').inputValue(),'');
 await candidate.getByRole('button',{name:'Получить моковый черновик'}).click();
 const candidateDraft=candidate.locator('[data-testid=assistant-draft]');
 await candidateDraft.locator('[name=description]').fill('Проверенное мной описание разработки iOS');
 const candidateAction=await candidateDraft.locator('form').getAttribute('action');
 await candidateDraft.getByRole('button',{name:'Проверил черновик — применить'}).click();
 await candidate.getByText('Проверенный черновик сохранён.',{exact:true}).waitFor();
 assert.equal(await candidate.locator('[name=description]').inputValue(),'Проверенное мной описание разработки iOS');
 await candidate.goto(url+'/assistant/');await candidate.getByRole('heading',{name:'Ваши последние черновики'}).waitFor();
 await candidate.locator(`a[href="${candidateAction}"]`).click();await candidate.getByText(/Черновик уже применён/).waitFor();
 assert.equal(await candidate.getByRole('button',{name:'Проверил черновик — применить'}).count(),0);
 const employer=await register('employer');
 await employer.goto(url+'/assistant/?mode=need');
 await employer.locator('[name=grade]').selectOption('Middle');
 await employer.locator('[name=skills]').fill('Swift, Core Data');
 await employer.getByRole('button',{name:'Получить моковый черновик'}).click();
 const draft=employer.locator('[data-testid=assistant-draft]');
 const action=await draft.locator('form').getAttribute('action');
 for(const [name,value] of Object.entries({title:'iOS браузерный сценарий',tasks:'Проверенные задачи команды',salary_min:'100000',salary_max:'200000',company_name:'Синтетическая команда',company_email:'team@demo.invalid'}))await draft.locator(`[name=${name}]`).fill(value);
 await draft.locator('[name=work_format]').selectOption('hybrid');
 await employer.setViewportSize({width:390,height:844});
 assert.equal(await employer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 fs.mkdirSync('.runtime/qa',{recursive:true});await employer.screenshot({path:'.runtime/qa/MVP-013-mobile.png',fullPage:true});
 await draft.getByRole('button',{name:'Проверил черновик — применить'}).click();
 await employer.getByText('По проверенному черновику создана новая потребность.',{exact:true}).waitFor();
 assert.equal(await employer.getByRole('link',{name:'iOS браузерный сценарий · Middle',exact:true}).count(),1);
 await employer.goto(url+action);await employer.getByText(/Черновик уже применён/).waitFor();
 const foreign=await employer.goto(url+candidateAction);assert.equal(foreign.status(),404);
 assert.deepEqual(errors,[]);
 const result={status:'PASS',url,scenarios:['registration_with_consent','candidate_edit_apply','owned_history_resume','read_only_replay','new_employer_without_need','need_edit_salary_company','need_saved','foreign_draft_404','mobile_no_overflow'],browserErrors:errors};
 fs.writeFileSync('.runtime/qa/MVP-013-browser.json',JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result,null,2));
 for(const context of contexts)await context.close();await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
